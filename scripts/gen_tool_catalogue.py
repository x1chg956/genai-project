"""Generate docs/tool_catalogue.md from the MCP servers themselves (docs/11 §8).

Each server is built in memory with fakes (no database, no network). For every tool the
catalogue lists its kind, description and input and output JSON schemas, and the tests
marked `@pytest.mark.tool("<name>")`. It fails when a tool has no kind tag, when its tag
disagrees with the R/C/W column in docs/05, when a schema is missing, or when no test is
marked for it. Run with `make docs-evidence`.
"""

from __future__ import annotations

import asyncio
import contextlib
import io
import json
import re
import sys
import tempfile
import warnings
from collections import defaultdict
from decimal import Decimal
from pathlib import Path
from typing import Any
from zoneinfo import ZoneInfo

import pytest
from fastmcp import Client, FastMCP

from auditguard.approval.records import ApprovalStore
from auditguard.config import REPO_ROOT, FormLimits, load_settings
from mcp_servers.aml_engine.engine.registry import load_rule_pack
from mcp_servers.aml_engine.server import build_server as build_aml
from mcp_servers.common.guard import ToolGuard
from mcp_servers.common.labels import KINDS
from mcp_servers.common.ledger import InMemoryLedgerRepo
from mcp_servers.filing_portal.db import PortalDb
from mcp_servers.filing_portal.server import build_server as build_portal
from mcp_servers.regulatory_kb.index import Bm25Index
from mcp_servers.regulatory_kb.server import build_server as build_kb
from mcp_servers.transactions.server import build_server as build_tx

OUT = REPO_ROOT / "docs" / "tool_catalogue.md"
SPEC = REPO_ROOT / "docs" / "05_MCP_SERVERS.md"
TESTS = REPO_ROOT / "tests" / "mcp_servers"
SERVERS = ("transactions", "aml_engine", "regulatory_kb", "filing_portal")
_ROW = re.compile(r"^\| (\w+) \|.*\| ([RCW])(?: \([^)]*\))? \| [^|]+ \|$")


def build_servers(tmp: Path) -> dict[str, FastMCP]:
    settings = load_settings(environ={"MCP_TOKEN_KEY": "catalogue"})
    guard = ToolGuard("catalogue", token_key=b"catalogue", allow_list={})
    repo = InMemoryLedgerRepo(alerts=[], transactions=[])
    tz = ZoneInfo(settings.timezone)
    approvals = tmp / "approvals.db"
    ApprovalStore(approvals)
    return {
        "transactions": build_tx(repo, guard, tz=tz, max_rows=settings.mcp.max_rows),
        "aml_engine": build_aml(
            repo, load_rule_pack(REPO_ROOT / "rules" / "IN", settings.rules.version), guard, tz=tz
        ),
        "regulatory_kb": build_kb(
            Bm25Index([]),
            guard,
            k_default=5,
            score_floor=Decimal(str(settings.retrieval.score_floor)),
        ),
        "filing_portal": build_portal(
            PortalDb(tmp / "portal.db"),
            ApprovalStore(approvals, read_only=True),
            guard,
            approval_key=b"catalogue",
            limits=FormLimits(max_payload_bytes=1, max_grounds_chars=1),
        ),
    }


async def list_tools(server: FastMCP) -> list[Any]:
    async with Client(server) as client:
        return list(await client.list_tools())


def spec_kinds(text: str) -> dict[str, str]:
    kinds: dict[str, str] = {}
    for line in text.splitlines():
        if match := _ROW.match(line.strip()):
            kinds[match.group(1)] = match.group(2)
    return kinds


class _Markers:
    def __init__(self) -> None:
        self.by_tool: dict[str, list[str]] = defaultdict(list)

    def pytest_collection_modifyitems(self, items: list[pytest.Item]) -> None:
        for item in items:
            for mark in item.iter_markers("tool"):
                self.by_tool[str(mark.args[0])].append(item.nodeid)


def marked_tests() -> dict[str, list[str]]:
    plugin = _Markers()
    args = ["--collect-only", "-qq", "-p", "no:cacheprovider", "-W", "ignore", str(TESTS)]
    with contextlib.redirect_stdout(io.StringIO()):
        code = pytest.main(args, plugins=[plugin])
    if code not in (0, 5):
        raise SystemExit(f"test collection failed (exit {code})")
    return {k: sorted(v) for k, v in plugin.by_tool.items()}


def tool_kind(tool: Any) -> str | None:
    tags = ((tool.meta or {}).get("fastmcp") or {}).get("tags") or []
    kinds = [KINDS[t] for t in tags if t in KINDS]
    return kinds[0] if len(kinds) == 1 else None


def schema_block(schema: dict[str, Any] | None) -> str:
    return "```json\n" + json.dumps(schema, indent=2, sort_keys=True) + "\n```"


def render(rows: list[dict[str, Any]]) -> str:
    out = [
        "<!-- Generated by scripts/gen_tool_catalogue.py (make docs-evidence). Do not edit. -->",
        "# Tool catalogue",
        "",
        "Every MCP tool, read from the servers themselves. Kind: R read, C compute, W write. "
        "Every call also carries `agent_token` and `case_id`, which the hooks layer fills in "
        "and hides from models (`docs/05`).",
        "",
        "| Server | Tool | Kind | Tests |",
        "|---|---|---|---|",
    ]
    out += [f"| {r['server']} | `{r['name']}` | {r['kind']} | {len(r['tests'])} |" for r in rows]
    for r in rows:
        out += [
            "",
            f"## `{r['name']}` ({r['server']}, {r['kind']})",
            "",
            r["description"],
            "",
            "**Input**",
            "",
            schema_block(r["input"]),
            "",
            "**Output**",
            "",
            schema_block(r["output"]),
            "",
            "**Tests**",
            "",
        ]
        out += [f"- `{t}`" for t in r["tests"]]
    return "\n".join(out) + "\n"


def main() -> int:
    warnings.filterwarnings("ignore")
    expected = spec_kinds(SPEC.read_text(encoding="utf-8"))
    tests = marked_tests()
    rows: list[dict[str, Any]] = []
    problems: list[str] = []
    with tempfile.TemporaryDirectory() as tmp:
        servers = build_servers(Path(tmp))
        for name in SERVERS:
            for tool in sorted(asyncio.run(list_tools(servers[name])), key=lambda t: t.name):
                kind = tool_kind(tool)
                if kind is None:
                    problems.append(
                        f"{tool.name}: needs exactly one of the tags read/compute/write"
                    )
                elif expected.get(tool.name) != kind:
                    problems.append(
                        f"{tool.name}: tagged {kind}, docs/05 says {expected.get(tool.name)}"
                    )
                if not tool.inputSchema or not tool.outputSchema:
                    problems.append(f"{tool.name}: missing input or output schema")
                if not tests.get(tool.name):
                    problems.append(f"{tool.name}: no test marked @pytest.mark.tool({tool.name!r})")
                rows.append(
                    {
                        "server": name,
                        "name": tool.name,
                        "kind": kind or "?",
                        "description": (tool.description or "").strip(),
                        "input": tool.inputSchema,
                        "output": tool.outputSchema,
                        "tests": tests.get(tool.name, []),
                    }
                )
    if problems:
        print("tool catalogue: FAIL", *problems, sep="\n  ", file=sys.stderr)
        return 1
    OUT.write_text(render(rows), encoding="utf-8")
    print(f"wrote {OUT.relative_to(REPO_ROOT)}: {len(rows)} tools")
    return 0


if __name__ == "__main__":
    sys.exit(main())
