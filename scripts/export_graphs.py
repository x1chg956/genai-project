"""Export the compiled graphs as Mermaid to docs/graph_<name>.md (docs/11 §8).

Each graph is built from the real code with inert dependencies: nothing calls a model, a
server or a database, so the diagram is exactly the wiring that runs. docs/03 §2 holds the
hand-written specification; these files are the evidence that the code matches it. Later
phases add C0 (fixed_workflow) and C2 (team) to GRAPHS. Run with `make docs-evidence`.
"""

from __future__ import annotations

import sys
import tempfile
from collections.abc import Callable
from pathlib import Path
from typing import Any

from langchain_core.language_models.fake_chat_models import FakeListChatModel
from langchain_core.runnables import RunnableLambda
from langgraph.checkpoint.memory import InMemorySaver

from auditguard.approval.records import ApprovalStore
from auditguard.config import REPO_ROOT, Settings, load_settings, resolve_path
from auditguard.graph.deps import GraphDeps
from auditguard.graph.single_agent import compile_graph
from auditguard.prompts import load_prompt
from auditguard.report.str_payload import load_reason_codes
from mcp_servers.common.guard import utcnow

DOCS = REPO_ROOT / "docs"


def inert_deps(settings: Settings, tmp: Path) -> GraphDeps:
    def no_clients(server: str) -> Any:
        raise RuntimeError("export_graphs never calls a server")

    return GraphDeps(
        settings=settings,
        clients=no_clients,
        approvals=ApprovalStore(tmp / "approvals.db"),
        reason_codes=load_reason_codes(resolve_path(settings.str_report.reason_codes)),
        chat_model=FakeListChatModel(responses=["unused"]),
        answer_model=RunnableLambda(lambda _: None),
        prompt=load_prompt("single_agent", settings),
        clock=utcnow,
    )


def c1(deps: GraphDeps) -> str:
    return compile_graph(deps, InMemorySaver()).get_graph(xray=1).draw_mermaid()


GRAPHS: dict[str, tuple[str, Callable[[GraphDeps], str]]] = {
    "c1": ("C1 single agent (`auditguard/graph/single_agent.py`), spec in docs/03 §2", c1),
}


def render(title: str, mermaid: str) -> str:
    return (
        "<!-- Generated by scripts/export_graphs.py (make docs-evidence). Do not edit. -->\n"
        f"# Graph: {title}\n\n"
        "Drawn by LangGraph from the compiled graph. Dotted edges are conditional.\n\n"
        f"```mermaid\n{mermaid.strip()}\n```\n"
    )


def main() -> int:
    settings = load_settings(environ={"TRACING_BACKEND": "none"})
    with tempfile.TemporaryDirectory() as tmp:
        deps = inert_deps(settings, Path(tmp))
        for name, (title, draw) in GRAPHS.items():
            out = DOCS / f"graph_{name}.md"
            out.write_text(render(title, draw(deps)), encoding="utf-8")
            print(f"wrote {out.relative_to(REPO_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
